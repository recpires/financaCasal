-- Remove as tabelas caso já existam (ignore os erros na 1ª execução)
DROP TABLE T_FC_RECEITA CASCADE CONSTRAINTS;
DROP TABLE T_FC_DESPESA CASCADE CONSTRAINTS;
DROP TABLE T_FC_META    CASCADE CONSTRAINTS;
DROP TABLE T_FC_USUARIO CASCADE CONSTRAINTS;

-- Usuário (cada membro do casal)
CREATE TABLE T_FC_USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO      VARCHAR2(100) NOT NULL,
    DS_EMAIL        VARCHAR2(120) NOT NULL,
    DT_NASCIMENTO   DATE,
    CONSTRAINT PK_FC_USUARIO PRIMARY KEY (ID_USUARIO)
);

-- Receita (entrada de dinheiro lançada por um usuário)
CREATE TABLE T_FC_RECEITA (
    ID_RECEITA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO      NUMBER        NOT NULL,
    DS_RECEITA      VARCHAR2(100) NOT NULL,
    DS_CATEGORIA    VARCHAR2(50),
    VL_RECEITA      NUMBER(12,2)  NOT NULL,
    DT_RECEITA      DATE          NOT NULL,
    CONSTRAINT PK_FC_RECEITA PRIMARY KEY (ID_RECEITA),
    CONSTRAINT FK_FC_RECEITA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_FC_USUARIO (ID_USUARIO),
    CONSTRAINT CK_FC_RECEITA_VALOR CHECK (VL_RECEITA > 0)
);

-- Despesa (saída de dinheiro lançada por um usuário)
CREATE TABLE T_FC_DESPESA (
    ID_DESPESA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO      NUMBER        NOT NULL,
    DS_DESPESA      VARCHAR2(100) NOT NULL,
    DS_CATEGORIA    VARCHAR2(50),
    VL_DESPESA      NUMBER(12,2)  NOT NULL,
    DT_DESPESA      DATE          NOT NULL,
    CONSTRAINT PK_FC_DESPESA PRIMARY KEY (ID_DESPESA),
    CONSTRAINT FK_FC_DESPESA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_FC_USUARIO (ID_USUARIO),
    CONSTRAINT CK_FC_DESPESA_VALOR CHECK (VL_DESPESA > 0)
);

-- Meta financeira do casal
CREATE TABLE T_FC_META (
    ID_META         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DS_META         VARCHAR2(100) NOT NULL,
    VL_ALVO         NUMBER(12,2)  NOT NULL,
    VL_ATUAL        NUMBER(12,2)  DEFAULT 0 NOT NULL,
    DT_LIMITE       DATE,
    CONSTRAINT PK_FC_META PRIMARY KEY (ID_META)
);
