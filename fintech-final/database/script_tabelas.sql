-- Remove as tabelas caso ja existam (ignore os erros na 1a execucao)
DROP TABLE T_FIN_TRANSACAO CASCADE CONSTRAINTS;
DROP TABLE T_FIN_CONTA     CASCADE CONSTRAINTS;
DROP TABLE T_FIN_CLIENTE   CASCADE CONSTRAINTS;
DROP TABLE T_FIN_USUARIO   CASCADE CONSTRAINTS;

-- Usuario do sistema (login)
CREATE TABLE T_FIN_USUARIO (
    ID_USUARIO      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO      VARCHAR2(100) NOT NULL,
    DS_EMAIL        VARCHAR2(120) NOT NULL,
    DS_SENHA_HASH   VARCHAR2(64)  NOT NULL,
    CONSTRAINT PK_FIN_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_FIN_USUARIO_EMAIL UNIQUE (DS_EMAIL)
);

-- Cliente (titular das contas)
CREATE TABLE T_FIN_CLIENTE (
    ID_CLIENTE      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NM_CLIENTE      VARCHAR2(100) NOT NULL,
    NR_CPF          CHAR(11)      NOT NULL,
    DS_EMAIL        VARCHAR2(120) NOT NULL,
    NR_TELEFONE     VARCHAR2(20),
    NR_IDADE        NUMBER(3)     NOT NULL,
    CONSTRAINT PK_FIN_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UK_FIN_CLIENTE_CPF UNIQUE (NR_CPF),
    CONSTRAINT CK_FIN_CLIENTE_IDADE CHECK (NR_IDADE >= 18)
);

-- Conta (corrente ou poupanca, identificada por TP_CONTA)
CREATE TABLE T_FIN_CONTA (
    ID_CONTA              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_CLIENTE            NUMBER(19)    NOT NULL,
    TP_CONTA              VARCHAR2(8)   NOT NULL,
    NR_CONTA              VARCHAR2(10)  NOT NULL,
    NR_AGENCIA            VARCHAR2(4)   NOT NULL,
    VL_SALDO              NUMBER(15,2)  NOT NULL,
    VL_LIMITE_CHEQUE      NUMBER(15,2),
    TX_RENDIMENTO_MENSAL  NUMBER(6,4),
    ST_ATIVA              NUMBER(1)     DEFAULT 1 NOT NULL,
    DT_ABERTURA           DATE          NOT NULL,
    CONSTRAINT PK_FIN_CONTA PRIMARY KEY (ID_CONTA),
    CONSTRAINT UK_FIN_CONTA_NUMERO UNIQUE (NR_CONTA),
    CONSTRAINT FK_FIN_CONTA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES T_FIN_CLIENTE (ID_CLIENTE),
    CONSTRAINT CK_FIN_CONTA_TIPO CHECK (TP_CONTA IN ('CORRENTE', 'POUPANCA')),
    CONSTRAINT CK_FIN_CONTA_ATIVA CHECK (ST_ATIVA IN (0, 1))
);

-- Transacao (extrato das contas)
CREATE TABLE T_FIN_TRANSACAO (
    ID_TRANSACAO    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_CONTA        NUMBER(19)    NOT NULL,
    TP_TRANSACAO    VARCHAR2(20)  NOT NULL,
    VL_TRANSACAO    NUMBER(15,2)  NOT NULL,
    DS_TRANSACAO    VARCHAR2(150) NOT NULL,
    DT_TRANSACAO    TIMESTAMP     NOT NULL,
    CONSTRAINT PK_FIN_TRANSACAO PRIMARY KEY (ID_TRANSACAO),
    CONSTRAINT FK_FIN_TRANSACAO_CONTA FOREIGN KEY (ID_CONTA) REFERENCES T_FIN_CONTA (ID_CONTA),
    CONSTRAINT CK_FIN_TRANSACAO_TIPO CHECK (TP_TRANSACAO IN ('DEPOSITO', 'RENDIMENTO', 'SAQUE', 'PAGAMENTO', 'TAXA')),
    CONSTRAINT CK_FIN_TRANSACAO_VALOR CHECK (VL_TRANSACAO > 0)
);
